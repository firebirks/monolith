//! File transfers in the desktop client, run by script (Phase 8): two
//! clients, each with a profile on disk, the real bridge and the real
//! runtime, on the mock Tor network, in real time. The script does what the
//! screens do when the user acts (a file dropped on the window, the actions
//! of the UI model) and waits for what the runtime says; nothing is
//! answered in its place. A picture of the window is written at each step:
//! `cargo run --release -p monolith-desktop --example files -- <dir>`.
//!
//! H. Two clients become contacts.
//! I. Bob drops a file on the conversation and sends it; Alice accepts it,
//!    both see it go and complete, and Alice saves it where she chooses:
//!    the bytes are those Bob's file had.
//! J. Alice's client stops while a large file arrives and starts again:
//!    the card says the transfer is being restored, never 0%, and it goes
//!    on from what was held, not from the start.
//! K. A file offered to Alice's Personal identity while she shows Work:
//!    Work shows nothing of it; Personal does once shown.

#![allow(
    clippy::print_stdout,
    clippy::expect_used,
    clippy::unwrap_used,
    clippy::panic,
    clippy::unreachable,
    clippy::arithmetic_side_effects,
    clippy::indexing_slicing,
    clippy::cast_possible_truncation
)]

mod common;

use std::path::{Path, PathBuf};
use std::time::Instant;

use core::time::Duration;

use common::Client;
use monolith_tor::MockNetwork;
use monolith_ui_model::{Dialog, Status, TransferKey, TransferPhase, UiContactId, UiTransferId};

const PATIENCE: Duration = Duration::from_secs(600);

fn start(network: &MockNetwork, name: &'static str, data: &Path, shots: &Path) -> Client {
    let network = network.clone();
    Client::start(
        name,
        data,
        move || network.backend(),
        common::in_memory_tor(),
        PATIENCE,
    )
    .with_pictures(shots)
}

fn scratch(dir: &Path, name: &str) -> PathBuf {
    let path = dir.join(name);
    let _ = std::fs::remove_dir_all(&path);
    path
}

/// A file of `len` generated bytes: no data of anyone's.
fn fixture(path: &Path, len: usize) -> Vec<u8> {
    let data: Vec<u8> = (0..len).map(|i| ((i * 31) % 251) as u8).collect();
    std::fs::write(path, &data).expect("write the fixture");
    data
}

/// The phase of the card of the transfer named `name` in the conversation
/// of `contact`, and its key.
fn card(client: &Client, contact: UiContactId, name: &str) -> Option<(TransferKey, TransferPhase)> {
    client
        .app
        .model
        .transfers_of(contact)
        .into_iter()
        .find(|item| item.name == name)
        .map(|item| (item.key, item.phase))
}

fn transfer_of(client: &Client, contact: UiContactId, name: &str) -> Option<UiTransferId> {
    match card(client, contact, name)? {
        (TransferKey::Transfer(transfer), _) => Some(transfer),
        _ => None,
    }
}

/// Saves the received file `transfer` of `client` at `destination`, as the
/// save dialog does when the user changes the place it suggests.
fn save(client: &mut Client, transfer: UiTransferId, destination: &Path, picture: &str) {
    client.model().open_save(transfer);
    client.until(
        "a place is suggested",
        |model| matches!(model.dialog(), Some(Dialog::SaveFile { place, .. }) if !place.is_empty()),
    );
    client.picture(picture);
    if let Some(Dialog::SaveFile { place, .. }) = client.model().dialog_mut() {
        *place = destination.display().to_string();
    }
    client.model().confirm();
    client.until("the file is saved", |model| model.dialog().is_none());
}

fn main() {
    let out = PathBuf::from(
        std::env::args()
            .nth(1)
            .unwrap_or_else(|| "files".to_owned()),
    );
    std::fs::create_dir_all(&out).expect("output folder");
    let data = std::env::temp_dir().join(format!("monolith-files-{}", std::process::id()));
    let data_a = scratch(&data, "a");
    let data_b = scratch(&data, "b");
    let files = scratch(&data, "files");
    let saved = scratch(&data, "saved");
    std::fs::create_dir_all(&files).unwrap();
    std::fs::create_dir_all(&saved).unwrap();
    let network = MockNetwork::new();
    let begun = Instant::now();

    println!("H. Two clients become contacts");
    let mut alice = start(&network, "alice", &data_a, &out);
    alice.open_profile();
    let personal = alice.create_identity("Personal");
    let invitation = alice.create_invitation("For Bob");
    alice.model().close();
    let mut bob = start(&network, "bob", &data_b, &out);
    bob.open_profile();
    bob.create_identity("Bob");
    let at_bob = bob.add_contact(&invitation, "Alice");
    bob.send(at_bob, "Hello Alice, it is Bob.");
    let request = alice.wait_request();
    let at_alice = alice.accept_request(request, "Bob");
    bob.wait_status(at_bob, "Hello Alice, it is Bob.", Status::Delivered);
    bob.until("Alice accepted", |model| model.can_offer(at_bob));
    bob.open_conversation(at_bob);
    alice.open_conversation(at_alice);

    println!("I. A file dropped, sent, accepted, received and saved");
    let report = files.join("project-report.pdf");
    let report_data = fixture(&report, 24_000_000);
    bob.drop_file(&report);
    bob.until(
        "the send dialog holds the dropped file",
        |model| matches!(model.dialog(), Some(Dialog::SendFile { path, .. }) if !path.is_empty()),
    );
    bob.picture("send-dialog");
    bob.model().confirm();
    bob.until_some(
        "Bob's card shows the file being prepared or offered",
        |client| card(client, at_bob, "project-report.pdf"),
    );
    bob.until("Bob's card waits for Alice", |model| {
        model
            .transfers_of(at_bob)
            .iter()
            .any(|item| item.phase == TransferPhase::Waiting)
    });
    bob.picture("offered");
    let offered = alice.until_some("Alice is offered the file", |client| {
        transfer_of(client, at_alice, "project-report.pdf").filter(|_| {
            card(client, at_alice, "project-report.pdf")
                .is_some_and(|(_, phase)| phase == TransferPhase::Offered)
        })
    });
    alice.picture("offer");
    alice.model().accept_transfer(offered);
    alice.until_some("Alice sees it on its way", |client| {
        card(client, at_alice, "project-report.pdf").and_then(|(_, phase)| match phase {
            TransferPhase::Transferring { bytes } if bytes > 0 => Some(()),
            TransferPhase::Received => Some(()),
            _ => None,
        })
    });
    alice.picture("receiving");
    alice.until("Alice holds the whole file", |model| {
        model
            .transfers_of(at_alice)
            .iter()
            .any(|item| item.phase == TransferPhase::Received)
    });
    bob.until("Bob sees it delivered", |model| {
        model
            .transfers_of(at_bob)
            .iter()
            .any(|item| item.phase == TransferPhase::Completed)
    });
    bob.picture("delivered");
    alice.picture("received");
    let destination = saved.join("report-from-bob.pdf");
    save(&mut alice, offered, &destination, "save-dialog");
    assert_eq!(std::fs::read(&destination).unwrap(), report_data);
    alice.until("the card says it was saved", |model| {
        model
            .transfers_of(at_alice)
            .iter()
            .any(|item| item.phase == TransferPhase::Saved)
    });
    alice.picture("saved");

    println!("J. Alice's client stops while a large file arrives, and starts again");
    let archive = files.join("photo-archive.zip");
    let archive_data = fixture(&archive, 200_000_000);
    bob.model()
        .open_send_file(at_bob, Some(archive.display().to_string()));
    bob.model().confirm();
    let prepared = bob.until_some("Bob's archive is prepared", |client| {
        card(client, at_bob, "photo-archive.zip").and_then(|(_, phase)| {
            matches!(phase, TransferPhase::Waiting | TransferPhase::Unsent(_)).then_some(phase)
        })
    });
    assert_eq!(prepared, TransferPhase::Waiting, "{prepared:?}");
    let large = alice.until_some("Alice is offered the archive", |client| {
        transfer_of(client, at_alice, "photo-archive.zip")
    });
    alice.model().accept_transfer(large);
    let before = alice.until_some("part of the archive arrived", |client| {
        card(client, at_alice, "photo-archive.zip").and_then(|(_, phase)| match phase {
            TransferPhase::Transferring { bytes } if bytes > 10_000_000 => Some(bytes),
            _ => None,
        })
    });
    alice.picture("archive-arriving");
    alice.close();
    let mut alice = start(&network, "alice", &data_a, &out);
    alice.open_profile();
    alice.model().select_identity(personal);
    alice.until("Personal is read", |model| {
        model.current_slice().is_some_and(|slice| slice.loaded)
    });
    alice.open_conversation(at_alice);
    // What the card says before the transfer goes on: never a share it
    // does not know.
    let restored = card(&alice, at_alice, "photo-archive.zip").map(|(_, phase)| phase);
    println!("  alice: the card after the restart: {restored:?}");
    assert!(
        matches!(
            restored,
            Some(TransferPhase::Restoring | TransferPhase::Transferring { .. })
        ),
        "{restored:?}"
    );
    if let Some(TransferPhase::Transferring { bytes }) = restored {
        assert!(bytes > 0, "the card shows 0 after the restart");
    }
    alice.picture("restoring");
    let resumed = alice.until_some("the archive goes on", |client| {
        card(client, at_alice, "photo-archive.zip").and_then(|(_, phase)| match phase {
            TransferPhase::Transferring { bytes } => Some(bytes),
            TransferPhase::Received => Some(u64::MAX),
            _ => None,
        })
    });
    println!("  alice: {before} bytes before the restart, {resumed} after it");
    assert!(resumed >= before, "it started again from the start");
    alice.picture("resumed");
    alice.until("Alice holds the whole archive", |model| {
        model
            .transfers_of(at_alice)
            .iter()
            .any(|item| item.name == "photo-archive.zip" && item.phase == TransferPhase::Received)
    });
    let destination = saved.join("archive.zip");
    let large = transfer_of(&alice, at_alice, "photo-archive.zip").unwrap();
    save(&mut alice, large, &destination, "archive-save-dialog");
    assert_eq!(std::fs::read(&destination).unwrap(), archive_data);
    alice.picture("archive-saved");

    println!("K. A file offered to Personal while Alice shows Work");
    let work = alice.create_identity("Work");
    alice.model().select_identity(work);
    alice.until("Work is read", |model| {
        model.current_slice().is_some_and(|slice| slice.loaded)
    });
    let notes = files.join("meeting-notes.txt");
    fixture(&notes, 40_000);
    bob.model()
        .open_send_file(at_bob, Some(notes.display().to_string()));
    bob.model().confirm();
    bob.until("the notes are offered", |model| {
        model
            .transfers_of(at_bob)
            .iter()
            .any(|item| item.name == "meeting-notes.txt" && item.phase == TransferPhase::Waiting)
    });
    // Late for the identity shown: Work holds nothing of it, and nothing
    // of Work changed.
    alice.pause(Duration::from_secs(5));
    assert_eq!(alice.app.model.current(), Some(work));
    let slice = alice.app.model.current_slice().unwrap();
    assert!(
        slice.transfers.is_empty(),
        "Work shows a transfer of Personal"
    );
    assert!(slice.contacts.iter().all(|view| view.id.identity() == work));
    alice.picture("work-untouched");
    alice.model().select_identity(personal);
    alice.open_conversation(at_alice);
    alice.until("Personal shows the offer", |model| {
        model
            .transfers_of(at_alice)
            .iter()
            .any(|item| item.name == "meeting-notes.txt" && item.phase == TransferPhase::Offered)
    });
    alice.picture("personal-offer");

    alice.close();
    bob.close();
    let _ = std::fs::remove_dir_all(&data);
    println!(
        "all file scenarios passed in {:.0} s; pictures in {}",
        begun.elapsed().as_secs_f64(),
        out.display()
    );
}
