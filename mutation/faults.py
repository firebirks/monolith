def crate_of(path):
    return path.split("/")[1]


def fault(fid, path, what, *pairs, group="", expect="caught"):
    return {
        "id": fid,
        "path": path,
        "what": what,
        "pairs": list(pairs),
        "group": group,
        "expect": expect,
        "crates": TESTS[crate_of(path)],
    }


